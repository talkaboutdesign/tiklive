/**
 * Generates packages/server/src/generated/assets.ts: the dashboard and overlays
 * from examples/overlays plus the built client (/tiklive.js), as base64 strings
 * decoded at module load. The standalone binary serves these.
 *
 * Run: bun scripts/embed-assets.ts (needs the client built first).
 *      bun scripts/embed-assets.ts --ensure   # write an empty placeholder if the file is missing (typecheck)
 */
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const overlaysDir = join(root, "examples", "overlays");
const clientBundle = join(root, "packages", "client", "dist", "tiklive.js");
const outFile = join(root, "packages", "server", "src", "generated", "assets.ts");

const listFiles = (dir: string): Array<string> =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });

export const embedAssets = (): { readonly count: number; readonly bytes: number } => {
  let bundle: Buffer;
  try {
    bundle = readFileSync(clientBundle);
  } catch {
    throw new Error(
      `Client bundle not found at ${clientBundle}. Build it first: bun run --filter @tiklive/client build`,
    );
  }

  const entries = new Map<string, Uint8Array>([["/tiklive.js", bundle]]);
  for (const file of listFiles(overlaysDir).sort()) {
    if (relative(overlaysDir, file) === "package.json") continue;
    const urlPath = "/" + relative(overlaysDir, file).split(sep).join("/");
    entries.set(urlPath, readFileSync(file));
  }

  const lines = [...entries].map(
    ([urlPath, bytes]) =>
      `  ${JSON.stringify(urlPath)}: ${JSON.stringify(Buffer.from(bytes).toString("base64"))},`,
  );
  const source = `// Generated by scripts/embed-assets.ts — do not edit.
const encoded: Record<string, string> = {
${lines.join("\n")}
};

const decode = (base64: string) => Uint8Array.from(atob(base64), (char) => char.charCodeAt(0));

export const assets: ReadonlyMap<string, Uint8Array> = new Map(
  Object.entries(encoded).map(([path, base64]) => [path, decode(base64)]),
);
`;
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, source);
  const bytes = [...entries.values()].reduce((sum, b) => sum + b.byteLength, 0);
  return { count: entries.size, bytes };
};

if (import.meta.main && process.argv.includes("--ensure")) {
  try {
    statSync(outFile);
  } catch {
    mkdirSync(dirname(outFile), { recursive: true });
    writeFileSync(
      outFile,
      "// Placeholder from scripts/embed-assets.ts --ensure. Run it without flags to embed real assets.\nexport const assets: ReadonlyMap<string, Uint8Array> = new Map();\n",
    );
  }
} else if (import.meta.main) {
  const { count, bytes } = embedAssets();
  console.log(`embedded ${count} files (${(bytes / 1024).toFixed(1)} KiB) into ${relative(root, outFile)}`);
}
